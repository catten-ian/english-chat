(function mergeShanghaiExamBank() {
  const records = (window.SHANGHAI_EXAM_BANK && window.SHANGHAI_EXAM_BANK.records) || [];
  if (typeof TRANSLATION_BANK === 'object' && TRANSLATION_BANK) {
    records.forEach(record => {
      const key = 'shanghai_' + record.year + '_' + record.season;
      TRANSLATION_BANK[key] = {
        label: record.label,
        items: (record.translation || []).map(item => ({
          zh: item.zh,
          ref: item.ref,
          words: item.words || []
        }))
      };
    });
  }
  if (typeof WRITING_TOPICS !== 'undefined' && Array.isArray(WRITING_TOPICS)) {
    const importedWriting = records
      .filter(record => record.writing)
      .map(record => '[' + record.label + '] ' + record.writing);
    WRITING_TOPICS.unshift(...importedWriting);
  }
})();
